// Writing otadata freezes the flash cache. The LVGL task stack lives in PSRAM
// (main.cpp: stack_in_psram), which is inaccessible while the cache is frozen and
// asserts in esp_cache_freeze_caches_disable_interrupts. So do the switch in a
// separate task whose stack is in internal RAM.
//
// The stack is reserved statically (.bss is internal RAM): creating the task can never fail
// for lack of memory. With WiFi, scans and fonts loaded, internal RAM can get too fragmented
// for a dynamic 4 KB stack, and the switch then silently stayed on "Starting AI Chat...".
#define SWITCH_STACK_SIZE 4096
static StackType_t s_switch_stack[SWITCH_STACK_SIZE / sizeof(StackType_t)];
static StaticTask_t s_switch_tcb;
static volatile bool s_switch_started;
static volatile esp_err_t s_switch_error = ESP_OK;

static void switch_task(void *arg)
{
    const esp_partition_t *partition = static_cast<const esp_partition_t *>(arg);
    ESP_UTILS_LOGI("Switching to %s (free internal RAM %u, largest block %u)", partition->label,
                   (unsigned)heap_caps_get_free_size(MALLOC_CAP_INTERNAL),
                   (unsigned)heap_caps_get_largest_free_block(MALLOC_CAP_INTERNAL));
    esp_err_t err = esp_ota_set_boot_partition(partition);
    if (err != ESP_OK) {
        ESP_UTILS_LOGE("Set boot partition failed: %s", esp_err_to_name(err));
        s_switch_error = err;           // Shown by onSwitchTimer()
        s_switch_started = false;
        vTaskDelete(nullptr);
        return;
    }
    ESP_UTILS_LOGI("Boot partition set, restarting");
    esp_restart();
}

// First call: start the switch. Then keeps polling, so a failure is shown instead of hanging.
void XiaoZhi::onSwitchTimer(lv_timer_t *timer)
{
    if (s_switch_error != ESP_OK) {
        lv_timer_delete(timer);
        if (_instance != nullptr && _instance->_hint_label != nullptr) {
            lv_obj_set_style_text_color(_instance->_hint_label, lv_color_hex(0xFF7043), 0);
            lv_label_set_text_fmt(_instance->_hint_label, "Switch failed: %s\nSwipe back to exit",
                                  esp_err_to_name(s_switch_error));
        }
        s_switch_error = ESP_OK;
        return;
    }
    if (s_switch_started) {
        return;                         // Waiting for the restart
    }
    s_switch_started = true;
    void *partition = lv_timer_get_user_data(timer);
    xTaskCreateStatic(switch_task, "to_xiaozhi", SWITCH_STACK_SIZE,  // ESP-IDF: stack depth in bytes
                      partition, 5, s_switch_stack, &s_switch_tcb);
}

bool XiaoZhi::run(void)
{
    ESP_UTILS_LOGD("Run");

    lv_obj_t *scr = lv_scr_act();
    lv_obj_set_style_bg_color(scr, lv_color_black(), 0);
    lv_obj_set_style_bg_opa(scr, LV_OPA_COVER, 0);

    _hint_label = lv_label_create(scr);
    lv_obj_set_style_text_font(_hint_label, &lv_font_montserrat_24, 0);
    lv_obj_set_style_text_align(_hint_label, LV_TEXT_ALIGN_CENTER, 0);
    lv_obj_align(_hint_label, LV_ALIGN_CENTER, 0, 0);

    const esp_partition_t *partition = find_xiaozhi_partition();
    if (partition == nullptr) {
        lv_obj_set_style_text_color(_hint_label, lv_color_hex(0xFF7043), 0);
        lv_label_set_text(_hint_label, "XiaoZhi not installed\nSwipe back to exit");
        return true;
    }

    lv_obj_set_style_text_color(_hint_label, lv_color_white(), 0);
    lv_label_set_text(_hint_label, "Starting AI Chat...");
    if (!s_switch_started) {
        lv_timer_create(onSwitchTimer, SWITCH_DELAY_MS, const_cast<esp_partition_t *>(partition));
    }

    return true;
}

bool XiaoZhi::back(void)
{
    ESP_UTILS_LOGD("Back");

    ESP_UTILS_CHECK_FALSE_RETURN(notifyCoreClosed(), false, "Notify core closed failed");

    return true;
}

