XiaoZhi *XiaoZhi::_instance = nullptr;

// Find the other OTA slot and check that it holds a XiaoZhi image
static const esp_partition_t *find_xiaozhi_partition()
{
    const esp_partition_t *partition = esp_ota_get_next_update_partition(nullptr);
    if (partition == nullptr) {
        ESP_UTILS_LOGE("No other OTA slot (is the dual-boot partition table flashed?)");
        return nullptr;
    }

    esp_app_desc_t desc = {};
    if (esp_ota_get_partition_description(partition, &desc) != ESP_OK) {
        ESP_UTILS_LOGE("Slot %s holds no valid app", partition->label);
        return nullptr;
    }
    if (strcmp(desc.project_name, XIAOZHI_PROJECT_NAME) != 0) {
        ESP_UTILS_LOGE("Slot %s holds '%s', not XiaoZhi", partition->label, desc.project_name);
        return nullptr;
    }
    ESP_UTILS_LOGI("Found XiaoZhi %s in slot %s", desc.version, partition->label);
    return partition;
}

void XiaoZhi::markRunningAppValid()
{
    esp_ota_img_states_t state = ESP_OTA_IMG_UNDEFINED;
    const esp_partition_t *running = esp_ota_get_running_partition();
    if ((esp_ota_get_state_partition(running, &state) == ESP_OK) && (state == ESP_OTA_IMG_PENDING_VERIFY)) {
        ESP_UTILS_LOGI("Mark launcher in slot %s as valid", running->label);
        esp_ota_mark_app_valid_cancel_rollback();
    }
}

XiaoZhi *XiaoZhi::requestInstance()
{
    if (_instance == nullptr) {
        _instance = new XiaoZhi();
    }
    return _instance;
}

