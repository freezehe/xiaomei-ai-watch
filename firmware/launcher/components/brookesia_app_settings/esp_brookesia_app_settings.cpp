void Settings::showPage(Page page)
{
    _page = page;
    lv_obj_add_flag(_page_password, LV_OBJ_FLAG_HIDDEN);
    lv_obj_add_flag(_page_joining, LV_OBJ_FLAG_HIDDEN);
    if (_sheet != nullptr) {
        lv_obj_delete(_sheet);
        _sheet = nullptr;
    }
    if (page == Page::PASSWORD) {
        lv_textarea_set_text(_pw_text, "");
        lv_textarea_set_password_mode(_pw_text, true);
        lv_label_set_text(_pw_title, _target.c_str());
        lv_obj_remove_flag(_page_password, LV_OBJ_FLAG_HIDDEN);
    } else if (page == Page::JOINING) {
        _last_join = -1;
        lv_obj_remove_flag(_page_joining, LV_OBJ_FLAG_HIDDEN);
        refreshJoin();
    }
}

// ---------------------------------------------------------------- network list
void Settings::rebuildList()
{
    if (_list == nullptr) {
        return;
    }
    sys_net_ap_t scan[SYS_NET_MAX_SCAN];
    int scan_count = sys_net_scan_results(scan, SYS_NET_MAX_SCAN);
    char saved[SYS_NET_MAX_SAVED][33];
    int saved_count = sys_net_saved(saved, SYS_NET_MAX_SAVED);
    const bool connected = sys_net_state() == SYS_NET_CONNECTED;
    _connected_ssid = connected ? sys_net_ssid() : "";

    // In range (strongest first), then saved networks not in range; the current one on top
    _rows.clear();
    for (int i = 0; i < scan_count; i++) {
        _rows.push_back({scan[i].ssid, scan[i].rssi, scan[i].secure, scan[i].saved, true});
    }
    for (int i = 0; i < saved_count; i++) {
        bool found = false;
        for (const Row &r : _rows) {
            found = found || r.ssid == saved[i];
        }
        if (!found) {
            _rows.push_back({saved[i], -100, true, true, false});
        }
    }
    for (size_t i = 1; i < _rows.size(); i++) {
        if (_rows[i].ssid == _connected_ssid) {
            Row r = _rows[i];
            _rows.erase(_rows.begin() + i);
            _rows.insert(_rows.begin(), r);
            break;
        }
    }

    lv_obj_clean(_list);
    for (size_t i = 0; i < _rows.size(); i++) {
        const Row &r = _rows[i];
        const bool current = !_connected_ssid.empty() && r.ssid == _connected_ssid;

        lv_obj_t *row = create_plain(_list);
        lv_obj_set_size(row, LV_PCT(100), 56);
        lv_obj_set_style_radius(row, 16, 0);
        lv_obj_set_style_pad_hor(row, 16, 0);
        lv_obj_set_style_bg_opa(row, LV_OPA_COVER, 0);
        lv_obj_set_style_bg_color(row, lv_color_hex(COLOR_CARD), 0);
        lv_obj_set_style_bg_color(row, lv_color_hex(COLOR_PRESSED), LV_STATE_PRESSED);
        lv_obj_set_flex_flow(row, LV_FLEX_FLOW_ROW);
        lv_obj_set_flex_align(row, LV_FLEX_ALIGN_START, LV_FLEX_ALIGN_CENTER, LV_FLEX_ALIGN_CENTER);
        lv_obj_set_style_pad_column(row, 10, 0);
        lv_obj_add_flag(row, LV_OBJ_FLAG_CLICKABLE);
        lv_obj_add_flag(row, LV_OBJ_FLAG_SCROLL_ON_FOCUS);
        lv_obj_add_event_cb(row, onRowClicked, LV_EVENT_CLICKED, (void *)(intptr_t)i);

        // Leading mark: check = connected, dot = saved
        lv_obj_t *mark = create_label(row, current ? COLOR_OK : COLOR_ACCENT, &lv_font_montserrat_18);
        lv_obj_set_width(mark, 18);
        lv_label_set_text(mark, current ? LV_SYMBOL_OK : (r.saved ? LV_SYMBOL_BULLET : ""));

        lv_obj_t *name = create_label(row, r.in_range ? COLOR_TEXT : COLOR_DIM);
        lv_obj_set_flex_grow(name, 1);
        lv_label_set_long_mode(name, LV_LABEL_LONG_MODE_DOTS);
        lv_label_set_text(name, r.ssid.c_str());

        if (r.in_range) {
            if (r.secure) {
                create_lock(row);
            }
            create_signal_bars(row, r.rssi);
        }   // Out of range: the dimmed name says it
    }
    if (_rows.empty()) {
        lv_obj_t *label = create_label(_list, COLOR_DIM);
        lv_obj_set_width(label, LV_PCT(100));
        lv_obj_set_style_text_align(label, LV_TEXT_ALIGN_CENTER, 0);
        lv_label_set_text(label, sys_net_scanning() ? "正在搜索…" : "没有找到网络");
    }
}

void Settings::showSheet(const Row &row, bool connected)
{
    _sheet_ssid = row.ssid;
    _sheet = create_plain(_screen);
    lv_obj_set_size(_sheet, LV_PCT(100), LV_PCT(100));
    lv_obj_set_style_bg_opa(_sheet, LV_OPA_80, 0);
    lv_obj_set_style_bg_color(_sheet, lv_color_hex(COLOR_BG), 0);
    lv_obj_add_flag(_sheet, LV_OBJ_FLAG_CLICKABLE);     // Swallow taps on the list below

    lv_obj_t *card = create_plain(_sheet);
    lv_obj_set_size(card, 300, LV_SIZE_CONTENT);
    lv_obj_center(card);
    lv_obj_set_style_radius(card, 26, 0);
    lv_obj_set_style_pad_all(card, 18, 0);
    lv_obj_set_style_bg_opa(card, LV_OPA_COVER, 0);
    lv_obj_set_style_bg_color(card, lv_color_hex(COLOR_CARD), 0);
    lv_obj_set_flex_flow(card, LV_FLEX_FLOW_COLUMN);
    lv_obj_set_flex_align(card, LV_FLEX_ALIGN_START, LV_FLEX_ALIGN_CENTER, LV_FLEX_ALIGN_CENTER);
    lv_obj_set_style_pad_row(card, 10, 0);

    lv_obj_t *title = create_label(card, COLOR_TEXT);
    lv_obj_set_width(title, LV_PCT(100));
    lv_obj_set_style_text_align(title, LV_TEXT_ALIGN_CENTER, 0);
    lv_label_set_long_mode(title, LV_LABEL_LONG_MODE_DOTS);
    lv_label_set_text(title, row.ssid.c_str());

    // user_data: 0 = connect, 1 = change password, 2 = forget, 3 = cancel
    struct { const char *text; uint32_t color; int action; bool show; } buttons[] = {
        {"连接", COLOR_ACCENT, 0, !connected && row.in_range},
        {"修改密码", COLOR_ROW, 1, row.in_range && row.secure},
        {"忘记此网络", COLOR_ERR, 2, true},
        {"取消", COLOR_ROW, 3, true},
    };
    for (const auto &b : buttons) {
        if (!b.show) {
            continue;
        }
        lv_obj_t *btn = createButton(card, b.text, b.color, 250, onSheetButton);
        lv_obj_set_height(btn, 50);
        lv_obj_set_user_data(btn, (void *)(intptr_t)b.action);
    }
}

void Settings::openRow(int index)
{
    if (index < 0 || index >= (int)_rows.size() || _sheet != nullptr) {
        return;
    }
    const Row &r = _rows[index];
    const bool connected = !_connected_ssid.empty() && r.ssid == _connected_ssid;
    if (r.saved || connected) {
        showSheet(r, connected);
    } else if (!r.secure) {
        startJoin(r.ssid, "");
    } else {
        _target = r.ssid;
        showPage(Page::PASSWORD);
    }
}

void Settings::startJoin(const string &ssid, const char *password)
{
    _target = ssid;
    sys_net_join(ssid.c_str(), password);
    showPage(Page::JOINING);
}

// ---------------------------------------------------------------- periodic refresh (LVGL task)
// Small Latin text uses Montserrat 18; anything that may contain Chinese (SSIDs, messages) uses
// the CJK font, which only exists at 30 px
static bool is_ascii(const char *s)
{
    for (; *s; s++) {
        if ((unsigned char)*s >= 0x80) {
            return false;
        }
    }
    return true;
}

static void set_mixed_text(lv_obj_t *label, const char *text, const lv_font_t *cjk)
{
    const lv_font_t *font = is_ascii(text) ? &lv_font_montserrat_18 : cjk;
    if (lv_obj_get_style_text_font(label, LV_PART_MAIN) != font) {
        lv_obj_set_style_text_font(label, font, 0);
    }
    set_text_if_changed(label, text);
}

void Settings::refreshStatus()
{
    const char *ssid = sys_net_ssid();
    char ip[16] = "";
    char detail[64];
    uint32_t dot = COLOR_OFF;
    string title;
    switch (sys_net_state()) {
    case SYS_NET_CONNECTED:
        dot = COLOR_OK;
        title = ssid;
        sys_net_ip(ip, sizeof(ip));
        snprintf(detail, sizeof(detail), "%s    %d dBm", ip, sys_net_rssi());
        break;
    case SYS_NET_CONNECTING:
        dot = COLOR_WARN;
        title = "正在连接…";
        snprintf(detail, sizeof(detail), "%s", ssid);
        break;
    case SYS_NET_FAILED:
        dot = COLOR_ERR;
        title = "未连接";
        snprintf(detail, sizeof(detail), "重试已保存的网络");
        break;
    case SYS_NET_NO_CONFIG:
        title = "未连接";
        snprintf(detail, sizeof(detail), "请选择下方网络");
        break;
    default:
        title = "Wi-Fi 未启动";
        detail[0] = '\0';
        break;
    }
    lv_obj_set_style_bg_color(_status_dot, lv_color_hex(dot), 0);
    set_text_if_changed(_status_title, title.c_str());
    set_mixed_text(_status_detail, detail, _font);

    const char *host = sys_net_server_host();
    char server[96];
    if (host[0]) {
        snprintf(server, sizeof(server), "OTA  %s", host);
    } else {
        snprintf(server, sizeof(server), "未设置服务器地址");
    }
    set_mixed_text(_server, server, _font);

    const bool scanning = sys_net_scanning();
    if (scanning == lv_obj_has_flag(_rescan_spinner, LV_OBJ_FLAG_HIDDEN)) {
        if (scanning) {
            lv_obj_remove_flag(_rescan_spinner, LV_OBJ_FLAG_HIDDEN);
            lv_obj_add_flag(_rescan_btn, LV_OBJ_FLAG_HIDDEN);
        } else {
            lv_obj_add_flag(_rescan_spinner, LV_OBJ_FLAG_HIDDEN);
            lv_obj_remove_flag(_rescan_btn, LV_OBJ_FLAG_HIDDEN);
        }
    }
}

void Settings::refreshJoin()
{
    const int state = sys_net_join_state();
    if (state == _last_join) {
        if (state == SYS_NET_JOIN_OK && lv_tick_elaps(_join_ok_tick) >= JOIN_OK_SHOW_MS) {
            showPage(Page::MAIN);
        }
        return;
    }
    _last_join = state;

    const bool busy = (state == SYS_NET_JOIN_BUSY);
    if (busy) {
        lv_obj_remove_flag(_join_spinner, LV_OBJ_FLAG_HIDDEN);
        lv_obj_add_flag(_join_icon, LV_OBJ_FLAG_HIDDEN);
        lv_obj_add_flag(_join_button, LV_OBJ_FLAG_HIDDEN);
    } else {
        lv_obj_add_flag(_join_spinner, LV_OBJ_FLAG_HIDDEN);
        lv_obj_remove_flag(_join_icon, LV_OBJ_FLAG_HIDDEN);
        lv_obj_remove_flag(_join_button, LV_OBJ_FLAG_HIDDEN);
    }

    string text;
    lv_obj_t *button_label = lv_obj_get_child(_join_button, 0);
    switch (state) {
    case SYS_NET_JOIN_BUSY:
        text = "正在连接\n" + _target;
        break;
    case SYS_NET_JOIN_OK:
        _join_ok_tick = lv_tick_get();
        lv_obj_add_flag(_join_button, LV_OBJ_FLAG_HIDDEN);
        lv_obj_set_style_text_color(_join_icon, lv_color_hex(COLOR_OK), 0);
        lv_label_set_text(_join_icon, LV_SYMBOL_OK);
        text = "已连接\n" + _target;
        break;
    case SYS_NET_JOIN_FAIL_AUTH:
        lv_obj_set_style_text_color(_join_icon, lv_color_hex(COLOR_ERR), 0);
        lv_label_set_text(_join_icon, LV_SYMBOL_CLOSE);
        lv_label_set_text(button_label, "重新输入");
        text = "密码错误";
        break;
    case SYS_NET_JOIN_FAIL_NOT_FOUND:
        lv_obj_set_style_text_color(_join_icon, lv_color_hex(COLOR_WARN), 0);
        lv_label_set_text(_join_icon, LV_SYMBOL_WARNING);
        lv_label_set_text(button_label, "返回");
        text = "找不到该网络\n请靠近路由器后重试";
        break;
    default:
        lv_obj_set_style_text_color(_join_icon, lv_color_hex(COLOR_ERR), 0);
        lv_label_set_text(_join_icon, LV_SYMBOL_CLOSE);
        lv_label_set_text(button_label, "返回");
        text = "连接失败";
        break;
    }
    lv_label_set_text(_join_text, text.c_str());
}

void Settings::refresh()
{
    const lv_font_t *font = music_font_get(&lv_font_montserrat_24);
    if (font != _font) {
        _font = font;
        lv_obj_set_style_text_font(_screen, _font, 0);  // Inherited by every label without its own font
    }

    refreshStatus();
    if (_page == Page::JOINING) {
        refreshJoin();
    }

    // Rebuild the list only when something it shows changed
    char saved[SYS_NET_MAX_SAVED][33];
    int saved_count = sys_net_saved(saved, SYS_NET_MAX_SAVED);
    string sig;
    for (int i = 0; i < saved_count; i++) {
        sig += saved[i];
        sig += '\n';
    }
    const string connected = (sys_net_state() == SYS_NET_CONNECTED) ? sys_net_ssid() : "";
    const uint32_t gen = sys_net_scan_gen();
    if (gen != _scan_gen || sig != _saved_sig || connected != _connected_ssid) {
        _scan_gen = gen;
        _saved_sig = sig;
        rebuildList();
    }
}

void Settings::onTimer(lv_timer_t *timer)
{
    Settings *app = static_cast<Settings *>(lv_timer_get_user_data(timer));
    if (app != nullptr && app->_screen != nullptr) {
        app->refresh();
    }
}

