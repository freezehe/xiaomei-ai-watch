// ---------------------------------------------------------------- small widgets
static void set_text_if_changed(lv_obj_t *label, const char *text)
{
    if (strcmp(lv_label_get_text(label), text) != 0) {
        lv_label_set_text(label, text);
    }
}

static lv_obj_t *create_plain(lv_obj_t *parent)
{
    lv_obj_t *obj = lv_obj_create(parent);
    lv_obj_remove_style_all(obj);
    lv_obj_remove_flag(obj, LV_OBJ_FLAG_SCROLLABLE);
    return obj;
}

static lv_obj_t *create_label(lv_obj_t *parent, uint32_t color, const lv_font_t *font = nullptr)
{
    lv_obj_t *label = lv_label_create(parent);
    lv_obj_set_style_text_color(label, lv_color_hex(color), 0);
    if (font != nullptr) {
        lv_obj_set_style_text_font(label, font, 0);
    }
    lv_label_set_text(label, "");
    return label;
}

static int signal_level(int rssi)
{
    return (rssi >= -55) ? 4 : (rssi >= -67) ? 3 : (rssi >= -77) ? 2 : 1;
}

// Four rising bars, like a phone's WiFi strength indicator
static void create_signal_bars(lv_obj_t *parent, int rssi)
{
    lv_obj_t *box = create_plain(parent);
    lv_obj_set_size(box, 22, 18);
    lv_obj_set_flex_flow(box, LV_FLEX_FLOW_ROW);
    lv_obj_set_flex_align(box, LV_FLEX_ALIGN_START, LV_FLEX_ALIGN_END, LV_FLEX_ALIGN_END);
    lv_obj_set_style_pad_column(box, 2, 0);
    int level = signal_level(rssi);
    for (int i = 0; i < 4; i++) {
        lv_obj_t *bar = create_plain(box);
        lv_obj_set_size(bar, 4, 6 + i * 4);
        lv_obj_set_style_radius(bar, 1, 0);
        lv_obj_set_style_bg_opa(bar, LV_OPA_COVER, 0);
        lv_obj_set_style_bg_color(bar, lv_color_hex(i < level ? COLOR_TEXT : COLOR_OFF), 0);
    }
}

// Small padlock drawn from two rectangles (the built-in symbol font has no lock)
static void create_lock(lv_obj_t *parent)
{
    lv_obj_t *box = create_plain(parent);
    lv_obj_set_size(box, 12, 17);
    lv_obj_t *shackle = create_plain(box);
    lv_obj_set_size(shackle, 8, 10);
    lv_obj_set_style_radius(shackle, 4, 0);
    lv_obj_set_style_border_width(shackle, 2, 0);
    lv_obj_set_style_border_color(shackle, lv_color_hex(COLOR_DIM), 0);
    lv_obj_align(shackle, LV_ALIGN_TOP_MID, 0, 0);
    lv_obj_t *body = create_plain(box);
    lv_obj_set_size(body, 12, 9);
    lv_obj_set_style_radius(body, 2, 0);
    lv_obj_set_style_bg_opa(body, LV_OPA_COVER, 0);
    lv_obj_set_style_bg_color(body, lv_color_hex(COLOR_DIM), 0);
    lv_obj_align(body, LV_ALIGN_BOTTOM_MID, 0, 0);
}

