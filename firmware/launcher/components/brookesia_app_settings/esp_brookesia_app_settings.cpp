void Settings::onSheetButton(lv_event_t *e)
{
    Settings *self = _instance;
    if (self == nullptr) {
        return;
    }
    const int action = (int)(intptr_t)lv_obj_get_user_data((lv_obj_t *)lv_event_get_current_target(e));
    const string ssid = self->_sheet_ssid;
    // Deleting the sheet from its own button's event is not allowed: do it asynchronously
    lv_obj_delete_async(self->_sheet);
    self->_sheet = nullptr;
    switch (action) {
    case 0:
        self->startJoin(ssid, nullptr);
        break;
    case 1:
        self->_target = ssid;
        self->showPage(Page::PASSWORD);
        break;
    case 2:
        sys_net_forget(ssid.c_str());
        break;
    default:
        break;
    }
}

void Settings::onKeyboard(lv_event_t *e)
{
    if (lv_event_get_code(e) == LV_EVENT_READY) {
        onPasswordConnect(e);
    } else {
        onPasswordCancel(e);
    }
}

void Settings::onEyeToggle(lv_event_t *e)
{
    if (_instance != nullptr) {
        lv_obj_t *ta = _instance->_pw_text;
        lv_textarea_set_password_mode(ta, !lv_textarea_get_password_mode(ta));
    }
}

void Settings::onPasswordCancel(lv_event_t *e)
{
    if (_instance != nullptr) {
        _instance->showPage(Page::MAIN);
    }
}

void Settings::onPasswordConnect(lv_event_t *e)
{
    Settings *self = _instance;
    if (self == nullptr) {
        return;
    }
    const char *pw = lv_textarea_get_text(self->_pw_text);
    if (strlen(pw) < 8) {               // WPA2/WPA3 passwords are 8..63 characters
        lv_textarea_set_placeholder_text(self->_pw_text, "8+ characters");
        return;
    }
    string password = pw;
    lv_textarea_set_text(self->_pw_text, "");
    self->startJoin(self->_target, password.c_str());
}

void Settings::onResultButton(lv_event_t *e)
{
    Settings *self = _instance;
    if (self == nullptr) {
        return;
    }
    if (sys_net_join_state() == SYS_NET_JOIN_FAIL_AUTH) {
        self->showPage(Page::PASSWORD);
    } else {
        self->showPage(Page::MAIN);
    }
}

// ---------------------------------------------------------------- app lifecycle
bool Settings::run(void)
{
    ESP_UTILS_LOGD("Run");
    if (!s_init_started) {
        s_init_started = true;
        xTaskCreate(init_task, "settings_init", 4 * 1024, nullptr, 4, nullptr);
    }
    _font = music_font_get(&lv_font_montserrat_24);

    _screen = lv_scr_act();
    lv_obj_set_style_bg_color(_screen, lv_color_hex(COLOR_BG), 0);
    lv_obj_set_style_bg_opa(_screen, LV_OPA_COVER, 0);
    lv_obj_set_style_text_font(_screen, _font, 0);
    lv_obj_remove_flag(_screen, LV_OBJ_FLAG_SCROLLABLE);

    buildMain(_screen);
    buildPassword(_screen);
    buildJoining(_screen);
    _sheet = nullptr;
    _page = Page::MAIN;
    lv_obj_add_flag(_page_password, LV_OBJ_FLAG_HIDDEN);
    lv_obj_add_flag(_page_joining, LV_OBJ_FLAG_HIDDEN);

    _scan_gen = sys_net_scan_gen();
    _saved_sig = "\x01";                // Force the first build
    refresh();
    sys_net_scan();
    lv_timer_create(onTimer, REFRESH_MS, this);
    return true;
}

bool Settings::back(void)
{
    ESP_UTILS_LOGD("Back");
    // Sub-page / sheet open: go back to the list instead of closing the app
    if (_screen != nullptr && (_page != Page::MAIN || _sheet != nullptr)) {
        showPage(Page::MAIN);
        return true;
    }
    // UI objects are recycled by the core
    _screen = _page_main = _page_password = _page_joining = nullptr;
    _status_dot = _status_title = _status_detail = _rescan_btn = _rescan_spinner = nullptr;
    _list = _server = _pw_title = _pw_text = nullptr;
    _join_spinner = _join_icon = _join_text = _join_button = _sheet = nullptr;
    ESP_UTILS_CHECK_FALSE_RETURN(notifyCoreClosed(), false, "Notify core closed failed");
    return true;
}

